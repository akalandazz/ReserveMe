// Юридические тексты: сведения об исполнителе, согласие на обработку ПДн и
// политика обработки ПДн (152-ФЗ). Одно место на оба приложения и на
// отдельную страницу privacy.html — экран согласия, «Об исполнителе» в
// «Важной информации» и политика не разойдутся.
//
// ⚠️ OPERATOR и STORAGE — заглушки, пока мастер не прислала данные.
// Меняете текст политики по существу — поднимите POLICY_VERSION в
// supabase/functions/_shared/consent.js: клиенты согласятся заново.
//
// Без React: privacy.html и экраны рендерят эти данные сами.

import { POLICY_VERSION } from "../supabase/functions/_shared/consent.js";

export { POLICY_VERSION };

/** Оператор ПДн и исполнитель услуг (Закон о защите прав потребителей, ст. 9). */
export const OPERATOR = {
  // ФИО полностью — так, как в документах.
  name: "[ФИО мастера]",
  // "Индивидуальный предприниматель" или "Плательщик налога на профессиональный доход (самозанятый)".
  status: "[ИП или самозанятый]",
  inn: "[ИНН]",
  // Только у ИП; самозанятому — пустая строка, строка не покажется.
  ogrnip: "[ОГРНИП]",
  address: "[Адрес оказания услуг]",
  // Куда писать запросы по персональным данным и отзыв согласия.
  contact: "[Telegram @логин и/или e-mail]",
};

/** Где лежит база — 152-ФЗ, ст. 18 ч. 5: первичная запись только в РФ. */
export const STORAGE = "[Провайдер и город сервера в России]";

/** Срок хранения, если согласие не отозвано раньше. */
export const RETENTION = "3 года с даты последней записи";

const MONTHS = [
  "января", "февраля", "марта", "апреля", "мая", "июня",
  "июля", "августа", "сентября", "октября", "ноября", "декабря",
];

/** "2026-10-03" → "3 октября 2026 г." — редакция политики на экране. */
export const POLICY_DATE = (() => {
  const [y, m, d] = POLICY_VERSION.split("-").map(Number);
  return MONTHS[m - 1] ? `${d} ${MONTHS[m - 1]} ${y} г.` : POLICY_VERSION;
})();

/** Строки «Об исполнителе»: [подпись, значение], пустые значения пропущены. */
export function operatorRows() {
  return [
    ["Исполнитель", OPERATOR.name],
    ["Статус", OPERATOR.status],
    ["ИНН", OPERATOR.inn],
    ["ОГРНИП", OPERATOR.ogrnip],
    ["Адрес", OPERATOR.address],
    ["Связь", OPERATOR.contact],
  ].filter(([, value]) => value);
}

const DATA_LIST = [
  "Telegram ID, имя, фамилия и имя пользователя (username) из профиля Telegram — их передаёт Telegram при входе;",
  "записи: услуга, дата, время, длительность, стоимость, статус и ваш комментарий;",
  "телефон и удобный способ связи — если вы сообщили их мастеру;",
  "заметки мастера о визитах;",
  "дата последнего входа и дата согласия с этой политикой.",
];

const PURPOSES = "запись на услуги, связь с вами по записи (подтверждение, перенос, отмена) и учёт визитов";

const ACTIONS =
  "сбор, запись, систематизация, накопление, хранение, уточнение, использование, удаление и уничтожение — с использованием средств автоматизации и без них";

/**
 * Текст согласия — отдельный документ (152-ФЗ, ст. 9, с 01.09.2025): не
 * внутри политики и не внутри других условий. Абзацы — для экрана согласия.
 */
export function consentParagraphs() {
  return [
    `Я даю согласие оператору — ${OPERATOR.name} (${OPERATOR.status}, ИНН ${OPERATOR.inn}, адрес: ${OPERATOR.address}) — на обработку моих персональных данных.`,
    `Цель: ${PURPOSES}.`,
    `Данные: Telegram ID, имя, фамилия и username из профиля Telegram; данные моих записей и комментарии к ним; телефон и способ связи, если я их сообщу; заметки мастера о визитах.`,
    `Действия: ${ACTIONS}. Данные хранятся на сервере в России (${STORAGE}) и третьим лицам не передаются.`,
    `Срок: ${RETENTION} или до отзыва согласия. Отозвать согласие можно в любой момент, написав мастеру: ${OPERATOR.contact}.`,
  ];
}

